"""
analysis/iso_countries.py

PR-ADS-165A — the COMPLETE ISO 3166-1 alpha-2 country table, as data.

Why this is a separate table from ``country_identity.SUPPORTED_COUNTRIES``.
That registry is deliberately a supported-MARKET list (96 codes): the revenue
pages group on it, and a code outside it is reported as unsupported. It is the
wrong table for the Google Ads → Countries page, where production spend falls
in 162 distinct ISO codes and the top lead countries include Nigeria, Kenya,
Uzbekistan and Somalia: resolved through the market registry most of that page
read "(unresolved location)" or "not matched".

All 249 officially assigned ISO 3166-1 alpha-2 codes, each with one plain
English display name, plus the other names a source emits for them
(``ISO_COUNTRY_NAME_ALIASES``): ISO's own inverted short names ("Korea,
Republic of"), former names HubSpot still stores ("Libyan Arab Jamahiriya",
"Swaziland", "Burma") and common spellings ("Ivory Coast", "Türkiye").

Deliberately ABSENT, because the text does not say which country is meant:
bare "Congo" (CG or CD) and bare "Virgin Islands" (VG or VI); and every
two-letter token that is not an established abbreviation of one country —
"CA" in a CRM country field is Canada or California, "IN" is India or
Indiana. Only "UK" and "US" (and "UAE", "KSA", "DRC", "PNG") are matched.

Two judgements, stated so they can be challenged:

* "Georgia" resolves to GE. The values resolved here come from a COUNTRY
  field (HubSpot's contact country); a US state is held in a different
  property. A state name that is not also a country ("California") matches
  nothing.
* bare "Korea" resolves to KR, as ``country_identity`` has always done.

Pure data. No dependency, no I/O. Resolve through
``analysis.country_identity.resolve_iso_country_text``.
"""

